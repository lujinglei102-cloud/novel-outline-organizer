/**
 * 分词（极简化）：
 * 1. 按中英文标点/空白切出片段
 * 2. 对每个中文片段用 nameVocab + plotVocab 做最大匹配
 * 3. 单字不返回（停用词也过滤）
 * 4. 未匹配的 2-3 字组合：仅当 isNameCandidate() 为 true 才作为候选词返回
 *    （避免"分手""误会"等情节词被当作人名候选）
 */
export function tokenize(text: string): string[] {
  const tokens: string[] = []
  const dict = [...nameVocab, ...plotVocab]
  const segs = text.split(/[\s，。！？；：、…—\-,.!?;:"'()（）\[\]【】《》<>、~`@#$%^&*+=/\\|0-9]+/)
  for (const seg of segs) {
    if (!seg) continue
    let i = 0
    while (i < seg.length) {
      let matched = false
      // 先尝试最长匹配（最长 4 字，递减到 2 字）
      for (let len = Math.min(4, seg.length - i); len >= 2; len--) {
        const w = seg.slice(i, i + len)
        if (dict.includes(w)) {
          tokens.push(w)
          i += len
          matched = true
          break
        }
        if (stopWords.has(w)) {
          i += len
          matched = true
          break
        }
      }
      if (!matched) {
        // 未匹配：尝试把连续 2 字作为人名候选（仅当像人名时才添加，避免情节词噪声）
        if (i + 2 <= seg.length) {
          const w = seg.slice(i, i + 2)
          if (!stopWords.has(w[0]) && !stopWords.has(w[1]) && isNameCandidate(w)) {
            tokens.push(w)
          }
        }
        i += 1
      }
    }
  }
  return tokens
}

