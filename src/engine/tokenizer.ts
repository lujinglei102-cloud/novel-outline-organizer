/**
 * 分词（极简化）：
 * 1. 按中英文标点/空白切出片段
 * 2. 对每个中文片段用 commonVocab 做最大匹配
 * 3. 单字不返回（停用词也过滤）
 * 4. 连续 2-4 字非字典匹配也作为候选词返回（辅助角色识别）
 */
export function tokenize(text: string): string[] {
  const tokens: string[] = []
  const segs = text.split(/[\s，。！？；：、…—\-,.!?;:"'()（）\[\]【】《》<>、~`@#$%^&*+=/\\|0-9]+/)
  for (const seg of segs) {
    if (!seg) continue
    let i = 0
    while (i < seg.length) {
      let matched = false
      for (let len = Math.min(4, seg.length - i); len >= 2; len--) {
        const w = seg.slice(i, i + len)
        if (commonVocab.includes(w) || stopWords.has(w)) {
          if (!stopWords.has(w)) tokens.push(w)
          i += len
          matched = true
          break
        }
      }
      if (!matched) {
        // 未匹配，尝试把连续 2-3 字作为候选（角色名可能性）
        if (i + 2 <= seg.length) {
          const w = seg.slice(i, i + 2)
          if (!stopWords.has(w[0]) && !stopWords.has(w[1])) tokens.push(w)
        }
        i += 1
      }
    }
  }
  return tokens
}

