// plotVocab 的 Set 形式，便于快速查找
const plotVocabSet = new Set(plotVocab)
const nameVocabSet = new Set(nameVocab)

export function isNameCandidate(word: string): boolean {
  if (!word || word.length < 2 || word.length > 4) return false
  // 在角色名词表中 → 通过
  if (nameVocabSet.has(word)) return true
  // 在情节词表中 → 直接拒绝（不再当作角色）
  if (plotVocabSet.has(word)) return false
  // 首字是姓氏 AND 每个字都是常见人名用字 → 通过
  if (!surnames.has(word[0])) return false
  for (let i = 1; i < word.length; i++) {
    if (stopWords.has(word[i])) return false
    if (!nameCharSet.has(word[i])) return false
  }
  return true
}
